pub fn projection_rule(type_name: &str, field_name: &str) -> Option<ProjectionRule> {
    PROJECTION_RULES
        .binary_search_by(|&(owner, field, _)| {
            owner.cmp(type_name).then_with(|| field.cmp(field_name))
        })
        .ok()
        .map(|index| PROJECTION_RULES[index].2)
}

pub fn declines(type_name: &str) -> bool {
    let start = PROJECTION_RULES.partition_point(|&(owner, _, _)| owner < type_name);
    PROJECTION_RULES[start..]
        .iter()
        .take_while(|&&(owner, _, _)| owner == type_name)
        .any(|&(_, _, rule)| matches!(rule, ProjectionRule::Decline))
}
