SEC_NUM_RE = re.compile(r'^[★⚠⛔✅\s]*(\d+(?:\.\d+)*[a-z]?)\b')
LINK_RE = re.compile(r'\[([^\]]*)\]\(([^)]*)\)')


def read_lines(path: Path) -> list[str]:
    return path.read_text(encoding='utf-8').splitlines()


def github_slug(heading: str, seen: Counter) -> str:
    """GitHub-flavored anchor slug of a heading's text.

    Formatting markers are removed first (code spans, bold/italic, link
    syntax), then everything except letters, digits, spaces, hyphens and
    underscores is dropped, spaces become hyphens (repeats preserved), and
    duplicate slugs get -1, -2, … suffixes.  Validated against the ledger's
    own intra-document hrefs by `register`.
    """
    text = LINK_RE.sub(lambda m: m.group(1), heading)
    text = text.replace('`', '')
    text = text.replace('**', '').replace('*', '')
    out = []
    for ch in text.lower():
        if ch.isalnum():
            # strip accents but keep unicode letters/digits like GitHub does
            out.append(ch)
        elif ch in ' -_':
            out.append(ch)
        # every other character (including ★ ⚠ — “ ” ' . , : ; # / ( ) [ ])
        # is dropped without a replacement
    slug = ''.join(out).replace(' ', '-')
    n = seen[slug]
    seen[slug] += 1
    return slug if n == 0 else f'{slug}-{n}'


class Heading:
    __slots__ = ('line', 'level', 'text', 'slug', 'key')

    def __init__(self, line, level, text, slug, key):
        self.line, self.level, self.text, self.slug, self.key = \
            line, level, text, slug, key


def parse_headings(lines: list[str]) -> list[Heading]:
    """All ##…###### headings with 1-based line numbers, slugs, and section
    keys.  Fenced code blocks are skipped so a ``#`` inside ``` fences can
    never be misread as a heading."""
    heads = []
    seen = Counter()
    in_fence = False
    for i, l in enumerate(lines):
        if l.lstrip().startswith('```'):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        m = re.match(r'(#{2,6})\s+(.*)$', l)
        if not m:
            continue
        text = m.group(2).strip()
        nm = SEC_NUM_RE.match(text)
        key = nm.group(1) if nm else None
        if key is None and text.lower().startswith('abstract'):
            key = 'abstract'
        heads.append(Heading(i + 1, len(m.group(1)), text,
                             github_slug(text, seen), key))
    return heads


class Ledger:
    def __init__(self, name: str, path: Path):
        self.name = name
        self.path = path
        self.lines = read_lines(path)
        self.headings = parse_headings(self.lines)
        self.by_key: dict[str, Heading] = {}
        for h in self.headings:
            if h.key is not None and h.key not in self.by_key:
                self.by_key[h.key] = h

    def resolve_key(self, key: str) -> Heading:
        """Exact section number, else prefix fallback (8.6.1a → 8.6.1 → 8.6),
        mirroring how the ledger's own register links target parents when a
        lettered subsection has no heading of its own."""
        k = key
        while True:
            if k in self.by_key:
                return self.by_key[k]
            if re.search(r'[a-z]$', k):
                k = k[:-1]
            elif '.' in k:
                k = k.rsplit('.', 1)[0]
            else:
                raise SystemExit(
                    f'mk_tables: section §{key} not found in {self.path.name}')

    def section_range(self, key: str) -> tuple[int, int]:
        """1-based inclusive line range of the section (with subsections):
        from its heading to the line before the next heading of equal or
        shallower level."""
        h = self.resolve_key(key)
        end = len(self.lines)
        started = False
        for h2 in self.headings:
            if h2 is h:
                started = True
                continue
            if started and h2.level <= h.level:
                end = h2.line - 1
                break
        return h.line, end

    def section_text(self, key: str) -> str:
        a, b = self.section_range(key)
        return '\n'.join(self.lines[a - 1:b])


