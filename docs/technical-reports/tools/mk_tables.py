def read_tsv(path: Path) -> tuple[list[str], list[dict[str, str]]]:
    header: list[str] = []
    rows: list[dict[str, str]] = []
    for raw in read_lines(path):
        if raw.startswith('#') or not raw.strip():
            continue
        cells = raw.split('\t')
        if not header:
            header = cells
            continue
        if len(cells) != len(header):
            raise SystemExit(f'mk_tables: {path.name}: row has {len(cells)} '
                             f'fields, header has {len(header)}: {raw[:60]}…')
        rows.append(dict(zip(header, cells)))
    if not header:
        raise SystemExit(f'mk_tables: {path} is empty')
    return header, rows


def curated_headline() -> list[dict[str, str]]:
    _, rows = read_tsv(CURATED['headline-metrics'])
    return rows


