def split_cells(row: str) -> list[str]:
    """Split a markdown table row on pipes that are neither escaped (``\\|``)
    nor inside a backtick code span.  Necessary because e.g. the SS-C9 row
    carries ``EPathMapRepr = Empty | Set(PathMap<()>) | Map(PathMap<Par>)``
    inside one code span."""
    cells, cur = [], []
    in_code = False
    i = 0
    while i < len(row):
        ch = row[i]
        if ch == '\\' and i + 1 < len(row):
            cur.append(row[i:i + 2])
            i += 2
            continue
        if ch == '`':
            in_code = not in_code
        if ch == '|' and not in_code:
            cells.append(''.join(cur))
            cur = []
        else:
            cur.append(ch)
        i += 1
    cells.append(''.join(cur))
    if cells and cells[0].strip() == '':
        cells = cells[1:]
    if cells and cells[-1].strip() == '':
        cells = cells[:-1]
    return [c.strip() for c in cells]


MATH_SUBS = [
    (r'\rightarrow', '→'), (r'\Rightarrow', '⇒'), (r'\leftrightarrow', '↔'),
    (r'\Theta', 'Θ'), (r'\approx', '≈'), (r'\geq', '≥'), (r'\leq', '≤'),
    (r'\times', '×'), (r'\neq', '≠'), (r'\max', 'max'), (r'\min', 'min'),
    (r'\operatorname', ''), (r'\mathrm', ''), (r'\text', ''),
]


def strip_md(text: str) -> str:
    """Light markdown/math normalization used only for the tool's own parsed
    view of register cells (the emitted fragments use the curated columns)."""
    def demath(m):
        s = m.group(1)
        for a, b in MATH_SUBS:
            s = s.replace(a, b)
        s = s.replace('{', '').replace('}', '').replace('\\', '')
        return s
    text = re.sub(r'\$`(.*?)`\$', demath, text)
    text = LINK_RE.sub(lambda m: m.group(1), text)
    text = text.replace('**', '').replace('*', '').replace('`', '')
    text = text.replace('\\|', '|')
    return unicodedata.normalize('NFC', ' '.join(text.split()))


class RegisterRow:
    __slots__ = ('ss_id', 'commit', 'repo', 'traversal', 'b0b1',
                 'class_change', 'section_text_', 'section_links', 'line')

    def __init__(self, **kw):
        for k, v in kw.items():
            setattr(self, k, v)


def parse_register(ss: Ledger) -> list[RegisterRow]:
    """Rows of §0's fix-register table, plus the prose-kept rejected
    candidate(s) (``SS-X…``) from the same section."""
    a, b = ss.section_range('0')
    rows = []
    id_re = re.compile(r'^\|\s*\*\*(SS-[A-Z]\d*)\*\*')
    for i in range(a - 1, b):
        line = ss.lines[i]
        m = id_re.match(line)
        if not m:
            continue
        cells = split_cells(line)
        if len(cells) != 7:
            raise SystemExit(
                f'mk_tables: register row at line {i + 1} split into '
                f'{len(cells)} cells (expected 7): {line[:80]}…')
        links = LINK_RE.findall(cells[6])
        rows.append(RegisterRow(
            ss_id=strip_md(cells[0]), commit=strip_md(cells[1]),
            repo=strip_md(cells[2]), traversal=strip_md(cells[3]),
            b0b1=strip_md(cells[4]), class_change=strip_md(cells[5]),
            section_text_=strip_md(cells[6]), section_links=links,
            line=i + 1))
    # SS-X… rejected candidates are kept in §0 prose, not in the table:
    # "**Rejected candidates** (kept in the register …): **SS-X1** …".
    table_ids = {r.ss_id for r in rows}
    x_re = re.compile(r'\*\*(SS-X\d+)\*\*')
    for i in range(a - 1, b):
        line = ss.lines[i]
        if line.startswith('|'):
            continue
        for xid in x_re.findall(line):
            if xid in table_ids:
                continue
            links = LINK_RE.findall(line)
            rows.append(RegisterRow(
                ss_id=xid, commit='', repo='', traversal=strip_md(line),
                b0b1='—', class_change='rejected',
                section_text_='; '.join(t for t, _ in links),
                section_links=links, line=i + 1))
            table_ids.add(xid)
    return rows


