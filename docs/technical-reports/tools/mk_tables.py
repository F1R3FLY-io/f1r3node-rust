def render_evidence(evidence: str, led: dict[str, Ledger]) -> str:
    """``stack-safety §5.17 + pathmap §5.4.1`` → markdown links into the
    ledgers.  A range like ``§5.1–§5.5`` is one link, anchored at the range's
    first section.  Anchors are built from the actual heading text."""
    parts = []
    for token in evidence.split(' + '):
        token = token.strip()
        m = re.match(r'(stack-safety|pathmap)\s+§(.+)$', token)
        if not m:
            raise SystemExit(f'mk_tables: unparseable evidence token: {token!r}')
        ledger_name, secs = m.group(1), m.group(2)
        first = re.split(r'[–-]', secs)[0].lstrip('§')
        slug = led[ledger_name].resolve_key(first).slug
        text = f'§{secs}' if ledger_name == 'stack-safety' else f'pathmap §{secs}'
        parts.append(f'[{text}]({LEDGER_RELPATH[ledger_name]}#{slug})')
    return ' + '.join(parts)


def esc_cell(text: str) -> str:
    return text.replace('|', '\\|')


def family_sort_key(ss_id: str) -> int:
    m = re.match(r'SS-[A-Z](\d+)$', ss_id)
    if m is None:
        raise ValueError(f'malformed SS id (expected SS-<letter><number>): {ss_id!r}')
    return int(m.group(1))


def family_of(ss_id: str) -> str:
    m = re.match(r'SS-([A-Z])', ss_id)
    if m is None:
        raise ValueError(f'malformed SS id (expected SS-<letter>...): {ss_id!r}')
    return m.group(1)


def mathify(text: str) -> str:
    """Wrap the mathematical symbols a curated cell may carry in GitHub-safe
    inline math spans (dollar-wrapped backtick spans), per the math-mathjax
    and math-symbol-literals guidelines. Curated cells stay human-readable in
    the TSV; the rendered table carries proper math. Handled forms, in order:
    a combined complexity transition, then lone Theta/O terms, arrows,
    inequalities, approximations, a leading Unicode minus on a percentage,
    and a numeric multiplier suffix."""
    sup = str.maketrans({'²': '^2', '³': '^3'})
    spans: list[str] = []

    def hold(span: str) -> str:
        spans.append(span)
        return f'\x00{len(spans) - 1}\x00'

    def theta_body(s: str) -> str:
        return s.translate(sup)

    def cls(sym: str) -> str:
        return '\\Theta' if sym == 'Θ' else 'O'

    # Θ/O(x) → Θ/O(y) as one span; each produced span is parked behind a
    # placeholder so later rules can never rewrap its interior
    text = re.sub(
        r'([ΘO])\(([^)]+)\) → ([ΘO])\(([^)]+)\)',
        lambda m: hold('$`' + cls(m.group(1)) + '(' + theta_body(m.group(2))
                       + ') \\rightarrow ' + cls(m.group(3))
                       + '(' + theta_body(m.group(4)) + ')`$'),
        text)
    text = re.sub(r'Θ\(([^)]+)\)',
                  lambda m: hold('$`\\Theta(' + theta_body(m.group(1)) + ')`$'),
                  text)
    text = re.sub(r'\bO\(([0-9a-zA-Z+^ ²³]{1,8})\)',
                  lambda m: hold('$`O(' + theta_body(m.group(1)) + ')`$'), text)
    text = re.sub('→', lambda _m: hold('$`\\rightarrow`$'), text)
    text = re.sub('≥', lambda _m: hold('$`\\geq`$'), text)
    text = re.sub('≤', lambda _m: hold('$`\\leq`$'), text)
    text = re.sub('≈', lambda _m: hold('$`\\approx`$'), text)
    text = re.sub(r'~(?=\d)', lambda _m: hold('$`\\approx`$') + ' ', text)
    text = re.sub(r'−([\d.]+)\s*%',
                  lambda m: hold(f'$`-{m.group(1)}\\%`$'), text)
    text = re.sub(r'(\d[\d,.]*)×',
                  lambda m: hold(f'$`{m.group(1)}\\times`$'), text)
    text = re.sub(r'\x00(\d+)\x00', lambda m: spans[int(m.group(1))], text)
    # a math span must not abut a preceding ASCII letter/digit (GitHub rule)
    text = re.sub(r'([0-9A-Za-z])\$`', r'\1 $`', text)
    return text


def build_family_fragments(led: dict[str, Ledger]) -> dict[str, str]:
    rows = curated_headline()
    by_family: dict[str, list[dict[str, str]]] = {f: [] for f in FAMILIES}
    for r in rows:
        by_family[r['family']].append(r)
    frags = {}
    for fam in FAMILIES:
        frows = sorted(by_family[fam], key=lambda r: family_sort_key(r['ss_id']))
        lines = ['| ID | Subject | Class | Control $`\\rightarrow`$ Final | '
                 'Disposition | Evidence |',
                 '|---|---|---|---|---|---|']
        for r in frows:
            lines.append('| {} | {} | {} | {} | {} | {} |'.format(
                esc_cell(r['ss_id']), mathify(esc_cell(r['subject'])),
                esc_cell(r['class']), mathify(esc_cell(r['control_final'])),
                mathify(esc_cell(r['disposition'])),
                render_evidence(r['evidence'], led)))
        frags[f'family-{fam}'] = '\n'.join(lines)
    return frags


def thousands(num: str) -> str:
    """6252 → 6,252 · 8060.736 → 8,060.736 · 32.00 → 32.00 (decimals kept
    verbatim; only the integer part is grouped, matching the ledger's §5.4
    presentation)."""
    m = re.fullmatch(r'(\d+)(\.\d+)?', num)
    if not m:
        return num
    return f'{int(m.group(1)):,}' + (m.group(2) or '')


def build_fixed_scale_fragment() -> str:
    lines_out = ['| Measurement | Unit | Set | Map |', '|---|---|---:|---:|']
    header = None
    for raw in read_lines(EPM1_TSV):
        if raw.startswith('#') or not raw.strip():
            continue
        cells = raw.split('\t')
        if header is None:
            header = cells
            if header != ['measurement', 'unit', 'set', 'map']:
                raise SystemExit(f'mk_tables: unexpected EPM1 TSV header: {header}')
            continue
        mid, unit, sval, mval = cells
        if mid not in MEASUREMENT_LABELS:
            raise SystemExit(f'mk_tables: measurement id {mid!r} missing from '
                             'MEASUREMENT_LABELS — update the constant from '
                             'the ledger §5.4 row names')
        lines_out.append('| {} | {} | {} | {} |'.format(
            MEASUREMENT_LABELS[mid], unit, thousands(sval), thousands(mval)))
    return '\n'.join(lines_out)


def wrap_fragment(name: str, body: str) -> str:
    return (MARKER_BEGIN.format(name=name) + '\n' + body + '\n'
            + MARKER_END.format(name=name) + '\n')


def all_fragments() -> dict[str, str]:
    led = ledgers()
    frags = build_family_fragments(led)
    frags['fixed-scale'] = build_fixed_scale_fragment()
    return frags


