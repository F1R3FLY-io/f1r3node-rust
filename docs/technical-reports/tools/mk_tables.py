# register-map: the disposition-map PlantUML source (Figure S7), derived from
# the curated register so the figure can never drift from the family tables.

MAP_PUML = TR_DIR / 'stack-safety/figures/register-disposition-map.puml'

FAMILY_TITLES = {
    'A': 'A — core traversals',
    'B': 'B — evaluator & async',
    'C': 'C — codecs',
    'D': 'D — deploy path',
    'E': 'E — the instrument',
    'F': 'F — mettail lowering',
    'G': 'G — mettail closures',
    'X': 'X — rejected',
    'Y': 'Y — defects (bad news)',
}

# (light fill, dark border) pairs from the ledger Appendix E.1 concept colours,
# light-background variants per the house figure legend convention
COL_DEPTH = ('C8E6C9', '2E7D32')    # converted, depth-axis class change
COL_WIDTH = ('BBDEFB', '1565C0')    # converted, width axis
COL_NEUTRAL = ('CFD8DC', '455A64')  # instrument / enabling / work-only /
                                    #   no class change / superseded
COL_DEFECT = ('FFE0B2', 'EF6C00')   # SS-Y rows: defects, open or discharged
COL_REJECT = ('FFCDD2', 'C62828')   # SS-X rows: rejected candidates


def cell_colour(row: dict[str, str]) -> tuple[str, str]:
    fam, cls = row['family'], row['class']
    disp = row['disposition'].lower()
    if fam == 'X':
        return COL_REJECT
    if fam == 'Y':
        return COL_DEFECT
    # An intermediate or explicitly non-class-change disposition is neutral
    # even when the row records a real improvement on another axis.
    if ('superseded' in disp or 'no class change' in disp or 'dormant' in disp
            or 'historical' in disp):
        return COL_NEUTRAL
    # A disposition that says "converted" wins over the class column: some
    # conversions were delivered on the work/heap axis (e.g. SS-G41, SS-G46
    # through SS-G49) and are conversions all the same.
    if 'converted' in disp:
        return COL_WIDTH if cls == 'width' else COL_DEPTH
    if cls in ('enabling', 'instrument', 'work'):
        return COL_NEUTRAL
    if cls == 'width':
        return COL_WIDTH
    return COL_DEPTH


def build_register_map() -> str:
    rows = curated_headline()
    if len(rows) != EXPECTED_TOTAL:
        raise SystemExit(f'register-map: curated rows {len(rows)} != '
                         f'{EXPECTED_TOTAL}')
    by_family: dict[str, list[dict[str, str]]] = {f: [] for f in FAMILIES}
    for r in rows:
        by_family[r['family']].append(r)
    for fam in FAMILIES:
        by_family[fam].sort(key=lambda r: family_sort_key(r['ss_id']))

    out = [
        '@startwbs',
        "' register-disposition-map.puml — Figure S7 of the stack-safety",
        "' technical report: all 96 stable SS identifiers at the snapshot",
        "' anchor, one cell each, coloured by final disposition.",
        "' GENERATED by tools/mk_tables.py register-map from",
        "' data/headline-metrics.tsv — do not hand-edit; regenerate with:",
        "'   python3 docs/technical-reports/tools/mk_tables.py register-map",
        "'   plantuml -tsvg docs/technical-reports/stack-safety/figures/register-disposition-map.puml",
        "' Colour legend (ledger Appendix E.1 light variants):",
        "'   green #C8E6C9 converted (depth) · blue #BBDEFB converted (width)",
        "'   slate #CFD8DC instrument/enabling/work-or-heap-axis-only/no-class-change/superseded",
        "'   amber #FFE0B2 SS-Y defect rows · red #FFCDD2 SS-X rejected",
        '<style>',
        'wbsDiagram {',
        '  node { LineColor #455A64; FontColor #212121; FontSize 12;',
        '         RoundCorner 8; Padding 4; }',
        '  arrow { LineColor #78909C; }',
        '}',
        '</style>',
        '* SS fix register — 96 stable identifiers\\n'
        'snapshot feature/mettail@9e44e570d',
    ]
    for fam in FAMILIES:
        fam_rows = by_family[fam]
        # Large families split into ten-cell columns; every column is a
        # top-level branch so WBS lays all columns out horizontally (leaves
        # with a side marker stack vertically beneath their branch header).
        chunks = ([fam_rows[i:i + 10] for i in range(0, len(fam_rows), 10)]
                  if len(fam_rows) > 12 else [fam_rows])
        for chunk in chunks:
            if len(chunks) > 1:
                first = chunk[0]['ss_id'].removeprefix('SS-')
                last = chunk[-1]['ss_id'].removeprefix('SS-')
                out.append(f'** {FAMILY_TITLES[fam]} ({len(fam_rows)})'
                           f'\\n{first}…{last}')
            else:
                out.append(f'** {FAMILY_TITLES[fam]} ({len(fam_rows)})')
            for r in chunk:
                fill = cell_colour(r)[0]
                out.append(f'***<[#{fill}] {r["ss_id"]}')
    out += [
        'legend right',
        '  |= cell |= final disposition |',
        '  |<#C8E6C9> | converted — depth-axis class change |',
        '  |<#BBDEFB> | converted — width axis |',
        '  |<#CFD8DC> | instrument / enabling / work-or-heap-axis only / no class change / superseded |',
        '  |<#FFE0B2> | SS-Y: defect row (allocated open; retained after repair) |',
        '  |<#FFCDD2> | SS-X: rejected candidate |',
        'endlegend',
        '@endwbs',
        '',
    ]
    return '\n'.join(out)


def cmd_register_map(_args) -> int:
    body = build_register_map()
    old = MAP_PUML.read_text() if MAP_PUML.exists() else None
    if old == body:
        print(f'unchanged: {MAP_PUML.relative_to(REPO_ROOT)}')
        return 0
    MAP_PUML.parent.mkdir(parents=True, exist_ok=True)
    MAP_PUML.write_text(body)
    print(f'written: {MAP_PUML.relative_to(REPO_ROOT)} '
          f'({len(body.splitlines())} lines)')
    return 0


