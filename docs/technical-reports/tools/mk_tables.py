#!/usr/bin/env python3
"""mk_tables.py — curated-data validator and markdown-table generator for the
2026-08-12 technical reports (stack-safety and PathMap/EPM1).

Roles
-----
1. Parse the stack-safety ledger's §0 fix register and cross-validate it
   against the curated master TSV (``headline-metrics.tsv``) — the two ID sets
   must be identical (96 IDs: 95 ``|``-table rows plus SS-X1, which the ledger
   keeps on the §0 "Rejected candidates" prose line rather than in the table).
2. Emit the per-family register tables and the EPM1 fixed-scale table as
   marker-wrapped markdown fragments for the technical-report writers.
3. Check that fragments embedded in the committed technical reports are
   byte-identical to freshly generated ones (``check``).
4. Verify the provenance of every curated TSV row: its ``source_quote`` must
   occur verbatim inside the ledger section named by its ``ledger_section``
   column (``provenance``).
5. Assert the register census (``coverage``).

Fragment contract
-----------------
Every fragment is wrapped in a marker pair::

    <!-- mk_tables:<name>:begin generated by tools/mk_tables.py — do not hand-edit -->
    ...table...
    <!-- mk_tables:<name>:end -->

where ``<name>`` is one of ``family-A`` … ``family-Y`` (hosted by the
stack-safety technical report) or ``fixed-scale`` (hosted by the PathMap
technical report).  TR writers paste the whole marker-wrapped block; ``check``
byte-compares the enclosed content and fails on any drift.

The ``.fragments/`` directory next to this script is TRANSIENT BUILD OUTPUT,
written on demand by ``emit`` and NOT committed — do not ``git add`` it.

Everything below uses the Python standard library only.
"""

