def cmd_provenance(_args) -> int:
    led = ledgers()
    total_missing = 0
    for name, path in CURATED.items():
        header, rows = read_tsv(path)
        for col in ('ledger_section', 'source_quote'):
            if col not in header:
                raise SystemExit(f'mk_tables: {path.name} lacks column {col}')
        ok = 0
        misses = []
        for r in rows:
            ledger_name, key = resolve_ledger_section(r['ledger_section'])
            text = led[ledger_name].section_text(key)
            quote = r['source_quote']
            if quote in text or quote.replace(NBSP, ' ') in text.replace(NBSP, ' '):
                ok += 1
            else:
                misses.append((r[header[0]], r['ledger_section'], quote))
        status = 'PASS' if not misses else 'FAIL'
        print(f'{status} {name}: {ok}/{len(rows)} quotes verified')
        for ident, sect, quote in misses:
            print(f'  MISS [{ident}] {sect}: {quote[:80]!r}')
        total_missing += len(misses)
    return 1 if total_missing else 0


def cmd_coverage(_args) -> int:
    led = ledgers()
    reg = parse_register(led['stack-safety'])
    reg_ids = [r.ss_id for r in reg]
    dup_reg = [i for i, c in Counter(reg_ids).items() if c > 1]
    cur = curated_headline()
    cur_ids = [r['ss_id'] for r in cur]
    dup_cur = [i for i, c in Counter(cur_ids).items() if c > 1]
    problems = []
    if dup_reg:
        problems.append(f'duplicate IDs in §0: {dup_reg}')
    if dup_cur:
        problems.append(f'duplicate IDs in curated TSV: {dup_cur}')
    if set(reg_ids) != set(cur_ids):
        problems.append(f'ID set mismatch: only-in-§0 '
                        f'{sorted(set(reg_ids) - set(cur_ids))}, only-in-curated '
                        f'{sorted(set(cur_ids) - set(reg_ids))}')
    for r in cur:
        m = re.match(r'SS-([A-Z])', r['ss_id'])
        if m is None:
            problems.append(f"malformed SS id in curated TSV: {r['ss_id']!r}")
            continue
        prefix = m.group(1)
        if r['family'] != prefix:
            problems.append(f"{r['ss_id']}: family column {r['family']!r} "
                            f'contradicts ID prefix {prefix!r}')
    census = Counter(family_of(i) for i in set(reg_ids))
    print('census by family (parsed from §0, SS-X from the rejected-candidates '
          'prose line):')
    for fam in FAMILIES:
        marker = '' if census.get(fam, 0) == EXPECTED_CENSUS[fam] else '  <-- DRIFT'
        print(f'  {fam}: {census.get(fam, 0)} (expected {EXPECTED_CENSUS[fam]})'
              f'{marker}')
    total = sum(census.values())
    print(f'  total: {total} (expected {EXPECTED_TOTAL}); '
          f'curated rows: {len(cur_ids)}')
    if dict(census) != EXPECTED_CENSUS or total != EXPECTED_TOTAL:
        problems.append(f'census drift: measured {dict(sorted(census.items()))} '
                        f'!= expected {EXPECTED_CENSUS}')
    if len(cur_ids) != EXPECTED_TOTAL:
        problems.append(f'curated row count {len(cur_ids)} != {EXPECTED_TOTAL}')
    if problems:
        for p in problems:
            print('VIOLATION: ' + p)
        return 1
    print(f'coverage OK: {EXPECTED_TOTAL}/{EXPECTED_TOTAL} — §0 ID set == '
          'curated ID set; every ID in exactly one family')
    return 0


