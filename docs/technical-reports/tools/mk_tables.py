def cmd_register(_args) -> int:
    led = ledgers()
    reg = parse_register(led['stack-safety'])
    reg_ids = {r.ss_id for r in reg}
    cur_ids = {r['ss_id'] for r in curated_headline()}
    missing = sorted(reg_ids - cur_ids)
    extra = sorted(cur_ids - reg_ids)
    if missing or extra:
        if missing:
            print(f'MISSING from curated headline-metrics.tsv: {missing}')
        if extra:
            print(f'EXTRA in curated headline-metrics.tsv (not in §0): {extra}')
        return 1
    print(f'register: §0 parse OK — {len(reg)} IDs, '
          f'curated set identical', file=sys.stderr)
    # Validate our computed anchors against the ledger's own intra-document
    # hrefs where the register row links into the stack-safety ledger itself.
    ss = led['stack-safety']
    checked = mismatched = 0
    for r in reg:
        for text, href in r.section_links:
            if not href.startswith('#'):
                continue
            nm = re.match(r'(\d+(?:\.\d+)*[a-z]?)', text)
            if not nm:
                continue
            checked += 1
            computed = ss.resolve_key(nm.group(1)).slug
            if computed != href[1:]:
                mismatched += 1
                print(f'note: {r.ss_id} register href #{href[1:]} vs computed '
                      f'#{computed} (ledger links a parent section)',
                      file=sys.stderr)
    print(f'register: anchor self-check {checked - mismatched}/{checked} '
          f'exact (mismatches are parent-section links, listed above)',
          file=sys.stderr)
    for name, body in build_family_fragments(led).items():
        print(wrap_fragment(name, body))
    return 0


def cmd_fixed_scale(_args) -> int:
    print(wrap_fragment('fixed-scale', build_fixed_scale_fragment()))
    return 0


def cmd_emit(_args) -> int:
    FRAGMENTS_DIR.mkdir(parents=True, exist_ok=True)
    for name, body in all_fragments().items():
        path = FRAGMENTS_DIR / f'{name}.md'
        path.write_text(wrap_fragment(name, body), encoding='utf-8')
        print(path)
    return 0


HOST_TR = dict([(f'family-{f}', None) for f in FAMILIES])


def fragment_host(name: str) -> Path:
    return PM_TR if name == 'fixed-scale' else SS_TR


def cmd_check(_args) -> int:
    failures = 0
    frags = all_fragments()
    host_cache: dict[Path, str | None] = {}
    for name in sorted(frags):
        host = fragment_host(name)
        if host not in host_cache:
            host_cache[host] = (host.read_text(encoding='utf-8')
                                if host.exists() else None)
        text = host_cache[host]
        if text is None:
            print(f'SKIP {name}: host TR not present yet '
                  f'({host.relative_to(REPO_ROOT)})')
            continue
        begin_prefix = f'<!-- mk_tables:{name}:begin'
        end_marker = MARKER_END.format(name=name)
        bi = text.find(begin_prefix)
        if bi < 0:
            print(f'SKIP {name}: marker pair not embedded in '
                  f'{host.relative_to(REPO_ROOT)} yet')
            continue
        bnl = text.find('\n', bi)
        ei = text.find(end_marker, bi)
        if bnl < 0 or ei < 0:
            print(f'FAIL {name}: begin marker without matching end marker')
            failures += 1
            continue
        embedded = text[bnl + 1:ei].rstrip('\n')
        if embedded == frags[name]:
            print(f'PASS {name}')
        else:
            print(f'FAIL {name}: embedded fragment differs from generated')
            failures += 1
    return 1 if failures else 0


def cmd_inject(_args) -> int:
    """Splice freshly generated fragments into the committed TRs in place —
    the inverse of `check`. Only the text between an existing marker pair is
    replaced; a TR or marker pair that is absent is skipped with a notice."""
    frags = all_fragments()
    edited: dict[Path, str] = {}
    injected = 0
    for name in sorted(frags):
        host = fragment_host(name)
        if host not in edited:
            if not host.exists():
                print(f'SKIP {name}: host TR not present '
                      f'({host.relative_to(REPO_ROOT)})')
                continue
            edited[host] = host.read_text(encoding='utf-8')
        text = edited.get(host)
        if text is None:
            continue
        begin_prefix = f'<!-- mk_tables:{name}:begin'
        end_marker = MARKER_END.format(name=name)
        bi = text.find(begin_prefix)
        if bi < 0:
            print(f'SKIP {name}: marker pair not embedded in '
                  f'{host.relative_to(REPO_ROOT)}')
            continue
        bnl = text.find('\n', bi)
        ei = text.find(end_marker, bi)
        if bnl < 0 or ei < 0:
            raise SystemExit(f'inject: {name} begin marker without matching '
                             f'end marker in {host}')
        edited[host] = text[:bnl + 1] + frags[name] + '\n' + text[ei:]
        injected += 1
        print(f'INJECT {name} -> {host.relative_to(REPO_ROOT)}')
    for host, text in edited.items():
        host.write_text(text, encoding='utf-8')
    print(f'{injected} fragment(s) injected')
    return 0


def resolve_ledger_section(token: str) -> tuple[str, str]:
    """'stack-safety §5.5.4' → ('stack-safety', '5.5.4');
    'stack-safety abstract' → ('stack-safety', 'abstract');
    'pathmap §5.5' → ('pathmap', '5.5')."""
    m = re.match(r'(stack-safety|pathmap)\s+(§?)(.+)$', token.strip())
    if not m:
        raise SystemExit(f'mk_tables: unparseable ledger_section: {token!r}')
    key = m.group(3).strip()
    if m.group(2) == '' and key.lower() != 'abstract':
        raise SystemExit(f'mk_tables: ledger_section without §: {token!r}')
    return m.group(1), (key.lower() if key.lower() == 'abstract' else key)


