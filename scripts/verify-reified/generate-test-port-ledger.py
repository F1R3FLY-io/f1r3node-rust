# Rows that replace the row of a rule for one test, keyed by `path::module::name`.
OVERRIDES = {}

PREFIXES = ("test_", "prop_", "e2e_", "regression_")


def humanize(name):
    for prefix in PREFIXES:
        if name.startswith(prefix):
            name = name[len(prefix):]
            break
    return name.replace("_", " ")


def successor(reference):
    alias, test = reference.split(":", 1)
    if alias not in FILES:
        raise SystemExit(f"unknown file alias {alias!r} in {reference!r}")
    return {"file": FILES[alias], "test": test}


def row_for(entry, spec):
    row = {
        "path": entry["path"],
        "module": entry["module"],
        "name": entry["name"],
        "kind": entry["kind"],
        "behavior": f"{spec['area']}: {humanize(entry['name'])}",
        "disposition": spec["d"],
        "successors": [successor(reference) for reference in spec["s"]],
    }
    if spec.get("r"):
        row["reason"] = spec["r"]
    if spec.get("nm"):
        row["positive_match"] = True
        row["non_match"] = [successor(reference) for reference in spec["nm"]]
    return row


def matches(spec, entry):
    if not re.search(spec["path"], entry["path"]):
        return False
    if spec["module"] is not None and entry["module"] != spec["module"]:
        return False
    return spec["name"] is None or re.fullmatch(spec["name"], entry["name"]) is not None


def build():
    inventory = json.loads(INVENTORY.read_text(encoding="utf-8"))
    used = [0] * len(RULES)
    rows = []
    unmatched = []
    for entry in inventory["tests"]:
        key = "::".join((entry["path"], entry["module"], entry["name"]))
        index = next((i for i, spec in enumerate(RULES) if matches(spec, entry)), None)
        if index is None:
            unmatched.append(key)
            continue
        used[index] += 1
        spec = dict(RULES[index], **OVERRIDES.get(key, {}))
        rows.append(row_for(entry, spec))
    unused = [f"{spec['path']} {spec['name']}" for spec, count in zip(RULES, used) if count == 0]
    for key in unmatched:
        print(f"generate: no rule matches {key}")
    for label in unused:
        print(f"generate: rule matches no entry: {label}")
    if unmatched or unused:
        raise SystemExit(1)
    return {
        "base": inventory["base"],
        "head": inventory["head"],
        "generator": "scripts/verify-reified/generate-test-port-ledger.py",
        "rows": rows,
    }


