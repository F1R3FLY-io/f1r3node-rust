"""Generate the test-port ledger of the legacy Reified RSpaces tests (P9 design v2, section 12).

The inventory `test-vectors/legacy-test-inventory-ff479042.json` lists the 1,181 tests that the
legacy stack 5c0363d9..ff479042 added. This script maps each inventory entry to one ledger row
through the rule table `RULES` below, and the table `OVERRIDES` replaces the row of one test.
It writes the expanded ledger `docs/rspace/reified-rspaces/verification/test-port-ledger.json`,
which `check-test-port-ledger.py` checks.

A rule names a legacy file (a regular expression over the path), the tests that it covers (a
regular expression over the name, `None` for every remaining test of the file, and an optional
expression over the module), an area, and the fields of the row:

* `d`: the disposition. `port` keeps the behavior, and the successor tests it. `retarget` keeps
  the purpose but changes the mechanism by a recorded decision, and the successor tests the new
  mechanism. `drop` removes the behavior, and the successor tests what replaces it.
* `s`: the successors, as `alias:test`. The aliases are the keys of `FILES`.
* `r`: the reason. A drop must name a decision or a plan section, and a retarget names the
  decision that changed the mechanism.
* `nm`: the non-match counterparts of a positive matcher test (plan section "Tests": every
  WildcardMatch-era positive test gains a non-match counterpart). A rule with `nm` marks its rows
  `positive_match`.

The first rule that matches an entry gives its row. Each entry must match a rule, and each rule
must match an entry, or the script fails.

Usage: python3 scripts/verify-reified/generate-test-port-ledger.py [--check]
With `--check`, the script compares the generated ledger with the committed ledger instead of
writing it.
"""
