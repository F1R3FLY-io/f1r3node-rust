//! Generated root-push properties for the RPB3 source projection.
//!
//! Intended as a test-only child of `protobuf_admission.rs`. The cases assert
//! facts about the actual checked push, using input-owned physical anchors and
//! the generated descriptor as independent expectations. They do not extract
//! a universal Rust-to-Verus state relation.

use proptest::prelude::*;

use super::*;
use crate::rust::rholang::canonical_bytes_arena::CanonicalLocatedByte;

fn assert_root_push<'a>(
    region: IndexedByteRegion<'a>,
    bytes: &[u8],
    expected_anchors: &[CanonicalByteProvenance],
    expected_end: CanonicalByteProvenance,
    program: &'static RhoMatchProgram,
    alternate_same_bytes: Option<IndexedByteRegion<'a>>,
) {
    assert_eq!(expected_anchors.len(), bytes.len());
    let expected_start = expected_anchors.first().copied().unwrap_or(expected_end);
    assert!(std::ptr::eq(
        wire_program_by_type_id(program.type_id).unwrap(),
        program
    ));
    let expected_path_slot = if std::ptr::eq(program, &EPATHMAP_RHO_MATCH_PROGRAM) {
        Some((3usize, 9u32))
    } else {
        None
    };
    let path_slots: Vec<_> = program
        .fields
        .iter()
        .enumerate()
        .filter_map(|(slot, field)| {
            matches!(field.kind, RhoMatchFieldKind::PathMap).then_some((slot, field.tag))
        })
        .collect();
    assert_eq!(path_slots.as_slice(), expected_path_slot.as_slice());

    let mut frames = Vec::with_capacity(1);
    let scores = CanonicalScoreArena::new();
    let mut stats = CanonicalProtobufAdmissionStats {
        input_bytes: bytes.len(),
        frame_variant_bytes: std::mem::size_of::<Frame>(),
        byte_native_validations: 1,
        ..CanonicalProtobufAdmissionStats::default()
    };
    let request = FrameRequest::Message { region, program };
    let source = RootInitializationSource::before_push(&request, &scores).unwrap();
    assert_eq!(source.request_kind, FrameRequestKind::Message);
    assert!(source
        .program
        .is_some_and(|selected| std::ptr::eq(selected, program)));
    assert_eq!(source.program_type_id, Some(program.type_id));
    assert_eq!(source.body_len, bytes.len());
    assert_eq!(source.region_start, Some(expected_start));
    assert_eq!(source.slot_count, program.fields.len());
    assert_eq!(source.score_entries, 0);

    let pushed = push_admission_frame(&mut frames, request.clone(), &mut stats).unwrap();
    assert!(request.matches_pushed_frame(&frames[0]));
    assert!(source.matches_root(&pushed, &frames, &scores));
    assert_eq!(pushed.before_len, 0);
    assert_eq!(pushed.after_len, 1);
    assert_eq!(stats.messages, 1);
    let Frame::Message(frame) = &frames[0] else {
        panic!("message request pushed another frame")
    };
    assert_eq!(frame.region_start, expected_start);
    let pushed_bytes: Vec<_> = frame.body.bytes().collect();
    assert_eq!(pushed_bytes.as_slice(), bytes);
    for (at, expected) in expected_anchors.iter().enumerate() {
        assert_eq!(frame.body.position_at(at).unwrap().physical, *expected);
    }
    assert_eq!(
        frame.body.position_at(bytes.len()).unwrap().physical,
        expected_end
    );
    assert_eq!(frame.cursor.logical_offset(), 0);
    assert_eq!(frame.slots.len(), program.fields.len());
    assert!(frame.slots.seen_slice().iter().all(|seen| !seen));
    assert!(frame.semantic_slots.iter().all(Vec::is_empty));
    if let Some((slot, tag)) = expected_path_slot {
        assert_eq!(program.fields[slot].tag, tag);
        assert_eq!(frame.slots.seen_at(slot), Some(false));
        assert!(frame.semantic_slots[slot].is_empty());
        if bytes.is_empty() {
            let mut finish_scores = CanonicalScoreArena::new();
            assert!(matches!(
                frame.finish(&mut finish_scores),
                Err(CanonicalProtobufAdmissionError::Schema { field: 9, .. })
            ));
        }
    }

    // These mutations isolate the constant-size request/frame checks; they
    // do not depend on parsing or reducing the generated byte content.
    if let Frame::Message(frame) = &mut frames[0] {
        frame.program = if std::ptr::eq(program, &SEND_RHO_MATCH_PROGRAM) {
            &EPATHMAP_RHO_MATCH_PROGRAM
        } else {
            &SEND_RHO_MATCH_PROGRAM
        };
    }
    assert!(!request.matches_pushed_frame(&frames[0]));
    if let Frame::Message(frame) = &mut frames[0] {
        frame.program = program;
        frame.region_start =
            CanonicalByteProvenance::new(expected_start.source, expected_start.offset + 1);
    }
    assert!(!request.matches_pushed_frame(&frames[0]));
    if let Frame::Message(frame) = &mut frames[0] {
        frame.region_start = expected_start;
    }

    if let Some(alternate) = alternate_same_bytes {
        let alternate_bytes: Vec<_> = alternate.bytes().collect();
        assert_eq!(alternate_bytes.as_slice(), bytes);
        assert_eq!(alternate.position_at(0).unwrap().physical, expected_start);
        if let Frame::Message(frame) = &mut frames[0] {
            frame.body = alternate.clone();
            frame.cursor = IndexedCanonicalFieldCursor::in_prost_slot_order(alternate);
        }
        assert!(!request.matches_pushed_frame(&frames[0]));
    }
}

proptest! {
    #![proptest_config(ProptestConfig::with_cases(48))]

    #[test]
    fn borrowed_root_push_binds_canonical_descriptor_and_backing(
        bytes in prop::collection::vec(any::<u8>(), 0..48),
        source in 1u32..1000,
        base in 0usize..100_000,
        use_pathmap in any::<bool>(),
    ) {
        let shadow = bytes.clone();
        let root = IndexedByteRegion::from_borrowed(&bytes, source, base);
        let alternate = (!bytes.is_empty()).then(|| {
            IndexedByteRegion::from_borrowed(&shadow, source, base)
        });
        let program = if use_pathmap {
            &EPATHMAP_RHO_MATCH_PROGRAM
        } else {
            &SEND_RHO_MATCH_PROGRAM
        };
        let anchors: Vec<_> = (0..bytes.len())
            .map(|at| CanonicalByteProvenance::new(source, base + at))
            .collect();
        let end = CanonicalByteProvenance::new(source, base + bytes.len());
        assert_root_push(root, &bytes, &anchors, end, program, alternate);
    }

    #[test]
    fn frozen_fragmented_root_push_preserves_every_physical_anchor(
        input in prop::collection::vec((any::<u8>(), 1u32..1000, 0usize..100_000), 2..40),
        end_source in 1_000u32..2_000,
        end_offset in 0usize..100_000,
        use_pathmap in any::<bool>(),
    ) {
        let mut arena = CanonicalBytesArena::new();
        let mut handle = arena.empty();
        let mut bytes = Vec::with_capacity(input.len());
        let anchors: Vec<_> = input.iter().enumerate()
            .map(|(at, (_, source, offset))| {
                CanonicalByteProvenance::new(2u32 * *source + (at % 2) as u32, *offset)
            })
            .collect();
        assert!(anchors.windows(2).all(|pair| pair[0].source != pair[1].source));
        for ((byte, _, _), anchor) in input.iter().zip(&anchors) {
            bytes.push(*byte);
            handle = arena.append(handle, CanonicalLocatedByte::new(*byte, *anchor)).unwrap();
        }
        let end = CanonicalByteProvenance::new(end_source, end_offset);
        let root = IndexedByteRegion::from_frozen(arena.freeze(handle), end);
        let program = if use_pathmap {
            &EPATHMAP_RHO_MATCH_PROGRAM
        } else {
            &SEND_RHO_MATCH_PROGRAM
        };
        assert_root_push(root, &bytes, &anchors, end, program, None);
    }

    #[test]
    fn composed_root_push_keeps_source_id_across_discontinuous_seam(
        bytes in prop::collection::vec(any::<u8>(), 2..40),
        cut_seed in any::<u8>(),
        left_source in 1u32..1000,
        right_source in 1_000u32..2_000,
        left_base in 0usize..100_000,
        right_base in 0usize..100_000,
        end_offset in 0usize..100_000,
        use_pathmap in any::<bool>(),
    ) {
        let cut = usize::from(cut_seed) % (bytes.len() - 1) + 1;
        let left = SourceTreeWindow::from_borrowed(&bytes[..cut], left_source, left_base).unwrap();
        let right = SourceTreeWindow::from_borrowed(&bytes[cut..], right_source, right_base).unwrap();
        let end = CanonicalByteProvenance::new(3_000, end_offset);
        let root = IndexedByteRegion::from_source(left.concat(&right).unwrap(), end);
        let anchors: Vec<_> = (0..bytes.len())
            .map(|at| if at < cut {
                CanonicalByteProvenance::new(left_source, left_base + at)
            } else {
                CanonicalByteProvenance::new(right_source, right_base + at - cut)
            })
            .collect();
        assert_eq!(root.position_at(cut).unwrap().physical,
            CanonicalByteProvenance::new(right_source, right_base));
        let program = if use_pathmap {
            &EPATHMAP_RHO_MATCH_PROGRAM
        } else {
            &SEND_RHO_MATCH_PROGRAM
        };
        assert_root_push(root, &bytes, &anchors, end, program, None);
    }

    #[test]
    fn empty_composed_root_push_uses_explicit_terminal_anchor(
        source in 1u32..1000,
        offset in 0usize..100_000,
    ) {
        let end = CanonicalByteProvenance::new(source, offset);
        let root = IndexedByteRegion::from_source(SourceTreeWindow::empty(), end);
        assert_root_push(root, &[], &[], end, &EPATHMAP_RHO_MATCH_PROGRAM, None);
    }

    #[test]
    fn empty_frozen_root_push_uses_explicit_terminal_anchor(
        source in 1u32..1000,
        offset in 0usize..100_000,
    ) {
        let arena = CanonicalBytesArena::new();
        let end = CanonicalByteProvenance::new(source, offset);
        let root = IndexedByteRegion::from_frozen(arena.freeze(arena.empty()), end);
        assert_root_push(root, &[], &[], end, &SEND_RHO_MATCH_PROGRAM, None);
    }
}
